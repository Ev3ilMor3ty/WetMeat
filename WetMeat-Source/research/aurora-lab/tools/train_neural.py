"""Train Aurora's own bounded, quantized residual evaluation on game-group splits."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import random
import time

import chess
import numpy as np
import torch
from torch import nn
from torch.nn import functional as F

BUCKETS = 8
FEATURES = BUCKETS * 768
HIDDEN = 64
FEATURE_SCALE = 256
OUTPUT_SCALE = 1024
CORRECTION_LIMIT = 400


def features(board):
    result = np.full((2, 32), FEATURES, dtype=np.int64)
    for perspective in [chess.WHITE, chess.BLACK]:
        row = 0 if perspective else 1
        orient = 0 if perspective else 56
        king = board.king(perspective) ^ orient
        transform = orient ^ (7 if chess.square_file(king) >= 4 else 0)
        normalized = board.king(perspective) ^ transform
        bucket = chess.square_rank(normalized) // 2 * 2 + chess.square_file(normalized) // 2
        for index, (square, piece) in enumerate(sorted(board.piece_map().items())):
            plane = piece.piece_type - 1 + (0 if piece.color == perspective else 6)
            result[row, index] = bucket * 768 + plane * 64 + (square ^ transform)
    return result


def fake_quantize(tensor, scale):
    rounded = torch.round(tensor * scale) / scale
    return tensor + (rounded - tensor).detach()


class ResidualNetwork(nn.Module):
    def __init__(self):
        super().__init__()
        self.embedding = nn.Embedding(FEATURES + 1, HIDDEN, padding_idx=FEATURES)
        nn.init.normal_(self.embedding.weight, std=0.015)
        with torch.no_grad():
            self.embedding.weight[FEATURES].zero_()
        self.bias = nn.Parameter(torch.full((HIDDEN,), 0.05))
        self.output = nn.Parameter(torch.empty(HIDDEN))
        nn.init.normal_(self.output, std=0.015)

    def forward(self, indices):
        inputs = F.embedding(indices, fake_quantize(self.embedding.weight, FEATURE_SCALE), padding_idx=FEATURES)
        accumulator = inputs.sum(dim=2) + fake_quantize(self.bias, FEATURE_SCALE)
        activation = accumulator.clamp(0, 1)
        difference = activation[:, 0] - activation[:, 1]
        raw = (difference * fake_quantize(self.output, OUTPUT_SCALE)).sum(dim=1)
        return CORRECTION_LIMIT * raw / (1 + raw.abs())


def quantized_correction(indices, weights, bias, output):
    inputs = weights[indices]
    accumulator = inputs.astype(np.int64).sum(axis=2) + bias.astype(np.int64)
    activation = np.clip(accumulator, 0, FEATURE_SCALE)
    raw = ((activation[:, 0] - activation[:, 1]) * output.astype(np.int64)).sum(axis=1)
    return np.trunc(CORRECTION_LIMIT * raw.astype(np.float64) /
                    (FEATURE_SCALE * OUTPUT_SCALE + np.abs(raw))).astype(np.int32)


def export(model, path, model_id):
    def integers(tensor, scale):
        values = np.rint(tensor.detach().cpu().numpy() * scale)
        if np.max(np.abs(values)) > 32767:
            raise ValueError("Quantized weights exceed int16 range")
        return values.astype(np.int16)
    weights = integers(model.embedding.weight, FEATURE_SCALE)
    bias = integers(model.bias, FEATURE_SCALE)
    output = integers(model.output, OUTPUT_SCALE)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as stream:
        stream.write("// Original Aurora residual model; generated by tools/train_neural.py.\n")
        stream.write("// Trained on numeric targets, without importing teacher code or weights.\n")
        stream.write("#pragma once\n#include <array>\n#include <cstdint>\n\nnamespace aurora::neural::weights {\n")
        stream.write("inline constexpr bool AVAILABLE = true;\n")
        stream.write(f'inline constexpr char MODEL_ID[] = "{model_id}";\n')
        for name, array in [("INPUT", weights[:FEATURES].reshape(-1)), ("BIAS", bias), ("OUTPUT", output)]:
            stream.write(f"inline constexpr std::array<std::int16_t, {array.size}> {name}{{{{\n")
            for start in range(0, array.size, 64):
                stream.write("    " + ",".join(str(int(value)) for value in array[start:start + 64]) + ",\n")
            stream.write("}};\n")
        stream.write("} // namespace aurora::neural::weights\n")
    return weights, bias, output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=35)
    parser.add_argument("--batch-size", type=int, default=512)
    parser.add_argument("--threads", type=int, default=3)
    parser.add_argument("--seed", type=int, default=20261007)
    parser.add_argument("--learning-rate", type=float, default=0.003)
    parser.add_argument("--header", type=Path, default=Path("src/generated/neural_weights.hpp"))
    parser.add_argument("--output", type=Path, default=Path("results/neural-training"))
    args = parser.parse_args()
    if min(args.epochs, args.batch_size, args.threads) < 1 or args.learning_rate <= 0:
        parser.error("Training parameters must be positive")
    torch.set_num_threads(args.threads)
    torch.set_num_interop_threads(1)
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    random.seed(args.seed)
    rows = [json.loads(line) for line in args.data.read_text().splitlines() if line.strip()]
    if len(rows) < 1000:
        parser.error("At least 1000 labelled positions are needed")
    indices = np.stack([features(chess.Board(row["fen"])) for row in rows])
    baseline = torch.tensor([row["baseline_white"] for row in rows], dtype=torch.float32)
    target = torch.tensor([row["target_white"] for row in rows], dtype=torch.float32)
    target_probability = torch.sigmoid(target / 400)
    groups = [row["group"] for row in rows]
    validation = np.array([int(hashlib.sha256((str(args.seed) + group).encode()).hexdigest()[:8], 16) % 5 == 0 for group in groups])
    train_indices = np.flatnonzero(~validation)
    validation_indices = np.flatnonzero(validation)
    if min(len(train_indices), len(validation_indices)) < 100:
        parser.error("Insufficient independent game groups for a train/validation split")
    assert not ({groups[i] for i in train_indices} & {groups[i] for i in validation_indices})
    inputs = torch.from_numpy(indices)
    model = ResidualNetwork()
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate, weight_decay=0.005)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs, eta_min=args.learning_rate * 0.1)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()

    def evaluate(use_network):
        model.eval()
        probabilities = []
        predictions = []
        with torch.no_grad():
            for start in range(0, len(validation_indices), args.batch_size):
                batch = validation_indices[start:start + args.batch_size]
                correction = model(inputs[batch]) if use_network else torch.zeros(len(batch))
                cp = baseline[batch] + correction
                probabilities.append(torch.sigmoid(cp / 400))
                predictions.append(cp)
        probabilities = torch.cat(probabilities)
        predictions = torch.cat(predictions)
        return {"probability_mse": F.mse_loss(probabilities, target_probability[validation_indices]).item(),
                "centipawn_mae": (predictions - target[validation_indices]).abs().mean().item()}

    original = evaluate(False)
    best = float("inf")
    best_epoch = 0
    best_state = None
    epochs = []
    print(f"Training {len(train_indices)} / validation {len(validation_indices)} positions; baseline {original}", flush=True)
    for epoch in range(1, args.epochs + 1):
        model.train()
        order = np.random.permutation(train_indices)
        losses = []
        for start in range(0, len(order), args.batch_size):
            batch = order[start:start + args.batch_size]
            correction = model(inputs[batch])
            probability = torch.sigmoid((baseline[batch] + correction) / 400)
            loss = F.mse_loss(probability, target_probability[batch])
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            losses.append(loss.item())
        scheduler.step()
        held_out = evaluate(True)
        if held_out["probability_mse"] < best:
            best = held_out["probability_mse"]
            best_epoch = epoch
            best_state = {key: value.detach().clone() for key, value in model.state_dict().items()}
        row = {"epoch": epoch, "training_mse": float(np.mean(losses)), "validation": held_out}
        epochs.append(row)
        print(f"Epoch {epoch}/{args.epochs}: train {row['training_mse']:.6f}; validation {held_out}; {time.monotonic() - started:.1f}s", flush=True)
    model.load_state_dict(best_state)
    dataset_sha = hashlib.file_digest(args.data.open("rb"), "sha256").hexdigest()
    model_id = f"aurora-residual-{dataset_sha[:12]}-epoch{best_epoch}"
    weights, bias, output = export(model, args.header, model_id)
    quantized = quantized_correction(indices[validation_indices], weights, bias, output)
    quantized_cp = baseline[validation_indices] + torch.from_numpy(quantized)
    quantized_metrics = {
        "probability_mse": F.mse_loss(torch.sigmoid(quantized_cp / 400), target_probability[validation_indices]).item(),
        "centipawn_mae": (quantized_cp - target[validation_indices]).abs().mean().item(),
    }
    # Cache-free golden vectors support exact verification of the independent C++ inference.
    vectors = []
    for index in validation_indices[:512]:
        delta = int(quantized_correction(indices[index:index + 1], weights, bias, output)[0])
        vectors.append({"fen": rows[index]["fen"], "correction_white": delta, "baseline_white": rows[index]["baseline_white"]})
    args.output.with_suffix(".vectors.json").write_text(json.dumps(vectors, indent=2) + "\n")
    torch.save({"state_dict": model.state_dict(), "model_id": model_id}, args.output.with_suffix(".pt"))
    metadata = {"model_id": model_id, "architecture": "8 king buckets, 12 piece planes, shared 64-neuron clipped accumulator, antisymmetric bounded residual",
                "correction_limit_cp": CORRECTION_LIMIT, "feature_scale": FEATURE_SCALE, "output_scale": OUTPUT_SCALE,
                "dataset_sha256": dataset_sha, "header_sha256": hashlib.file_digest(args.header.open("rb"), "sha256").hexdigest(),
                "seed": args.seed, "positions": len(rows), "training_positions": len(train_indices), "validation_positions": len(validation_indices),
                "train_groups": len({groups[i] for i in train_indices}), "validation_groups": len({groups[i] for i in validation_indices}),
                "best_epoch": best_epoch, "baseline_validation": original, "quantized_validation": quantized_metrics,
                "elapsed_seconds": round(time.monotonic() - started, 3), "epochs": epochs,
                "notes": ["Entire model trained here from original numeric-label dataset.",
                          "Validation is grouped by complete games; no game group appears in both partitions.",
                          "Label agreement does not establish playing strength; paired engine matches are required."]}
    args.output.with_suffix(".json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps({key: value for key, value in metadata.items() if key != "epochs"}, indent=2))
    if quantized_metrics["probability_mse"] >= original["probability_mse"]:
        raise SystemExit("Exported network did not improve held-out label agreement")


if __name__ == "__main__":
    main()
